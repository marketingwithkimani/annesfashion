-- 11. CHAT CONVERSATIONS TABLE
CREATE TABLE IF NOT EXISTS public.chat_conversations (
    id VARCHAR(50) PRIMARY KEY,
    session_id VARCHAR(100) NOT NULL,
    customer_name VARCHAR(100) DEFAULT 'Guest Customer',
    customer_email VARCHAR(100) NULL,
    customer_phone VARCHAR(20) NULL,
    current_product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    current_product_title VARCHAR(250) NULL,
    current_page VARCHAR(250) NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'AI_ACTIVE',
    assigned_staff_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    assigned_staff_name VARCHAR(100) NULL,
    last_message TEXT NULL,
    last_message_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_chat_conv_session ON public.chat_conversations(session_id);
CREATE INDEX IF NOT EXISTS idx_chat_conv_status ON public.chat_conversations(status);

-- 12. CHAT MESSAGES TABLE
CREATE TABLE IF NOT EXISTS public.chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id VARCHAR(50) NOT NULL REFERENCES public.chat_conversations(id) ON DELETE CASCADE,
    sender_type VARCHAR(20) NOT NULL,
    sender_name VARCHAR(100) NOT NULL,
    sender_id VARCHAR(100) NULL,
    content TEXT NOT NULL,
    metadata TEXT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_chat_msg_conv ON public.chat_messages(conversation_id);

-- ENABLE ROW LEVEL SECURITY FOR CHAT TABLES
ALTER TABLE public.chat_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chat_messages ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow all select chat_conversations" ON public.chat_conversations FOR SELECT USING (true);
CREATE POLICY "Allow all insert chat_conversations" ON public.chat_conversations FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow all update chat_conversations" ON public.chat_conversations FOR UPDATE USING (true);

CREATE POLICY "Allow all select chat_messages" ON public.chat_messages FOR SELECT USING (true);
CREATE POLICY "Allow all insert chat_messages" ON public.chat_messages FOR INSERT WITH CHECK (true);

